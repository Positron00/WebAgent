logger = logging.getLogger(__name__)

# Prompt for the Coding Review Agent
CODING_REVIEW_PROMPT = """You are a Coding Review Agent specializing in reviewing, executing, debugging, and fixing Python code.

ORIGINAL QUERY: {query}
GENERATED CODE: {code}
CODE EXECUTION RESULT: {execution_result}
ERROR DETAILS: {error_details}

Your task:
1. Review the generated code for:
   - Code quality (readability, structure, best practices)
   - Potential bugs or errors
   - Performance issues
   - Security concerns
2. Execute the code and analyze the results
3. Debug any issues found
4. Fix the code if necessary

REVIEW GUIDELINES:
- Identify both strengths and weaknesses in the code
- Be specific about any issues found
- Consider edge cases and error handling
- Suggest concrete improvements

If the code execution failed or produced errors:
1. Identify the root cause of the error
2. Explain the issue in simple terms
3. Provide a fixed version of the code

Your response should have the following format:

REVIEW:
A comprehensive review of the code, focusing on code quality, potential issues, and suggestions for improvement.

EXECUTION ANALYSIS:
Analysis of the code execution results, including any errors or unexpected behaviors.

FIXED CODE:
```python
# Your improved and fixed version of the code here
```

IMPROVEMENT EXPLANATION:
A brief explanation of the changes made and why they improve the code.
"""

# Static prompt text is never scored by the safety net (SEC-032).
register_template("coding_review", CODING_REVIEW_PROMPT)

class CodingReviewAgent(BaseAgent):
    """
    Coding Review Agent that reviews, executes, debugs, and fixes code.
    """
    
    def __init__(self):
        """Initialize the Coding Review Agent."""
        super().__init__(name="coding_review")
        
        # Get configuration for allowed modules
        agents_config = get_agents_config()
        self.allowed_libraries = ", ".join(agents_config.coding.allowed_modules) if hasattr(agents_config, "coding") else "matplotlib, seaborn, pandas, numpy"
        self.timeout_seconds = getattr(agents_config.coding, "timeout_seconds", 30) if hasattr(agents_config, "coding") else 30
        
        self.llm = get_agent_llm("coding_review")
        self.openai_llm = getattr(self.llm, "inner", self.llm)
        self.code_cleaner_model = getattr(self.llm, "inner", self.llm)
    

    async def run(self, state: WorkflowState) -> WorkflowState:
        """
        Run the Coding Review Agent on the current workflow state.
        
        Args:
            state: The current workflow state
            
        Returns:
            Updated workflow state with code review and fixes
        """
        try:
            logger.info(f"Coding Review Agent processing query ({describe_text(state.query)})")
            if settings.WEBAGENT_ENV == "dev":
                logger.debug("Query: %s", state.query)
            
            # Extract code from the coding_assistant report
            coding_report = state.reports.get("coding_assistant", {})
            code = coding_report.get("code", "")
            
            # Clean up code if it contains markdown formatting
            clean_code = self.clean_code(code)
            
            # Execute the code and get results
            purpose = str(coding_report.get("explanation") or "")
            success, execution_result = self.execute_python_code(clean_code, state, scored_text=purpose)
            
            # Prepare error details
            error_details = execution_result if not success else ""
            
            # Create the review prompt
            prompt_dict = {
                "query": state.query,
                "code": clean_code,
                "execution_result": execution_result,
                "error_details": error_details
            }
            
            # Generate the code review using LLM
            logger.info("Generating code review and fixes")
            hop = await acheck_hop(
                "coding_review",
                task_items(state)
                + [
                    ContextItem("agent_output", clean_code, ref="coding_assistant"),
                    ContextItem("tool_output", str(execution_result), ref="execute_code"),
                    ContextItem("tool_output", str(error_details), ref="execute_code_errors"),
                ],
                state,
            )
            # Execution output is untrusted (the generated code wrote it): use what checkpoint 1 kept.
            prompt_dict["execution_result"] = kept_text(hop, "execute_code", str(execution_result))
            prompt_dict["error_details"] = kept_text(hop, "execute_code_errors", str(error_details))
            review_result = await self._generate_review(prompt_dict)
            
            # Extract parts from the review result
            review = self.extract_section(review_result, "REVIEW")
            execution_analysis = self.extract_section(review_result, "EXECUTION ANALYSIS")
            fixed_code = self.extract_code(review_result)
            improvement_explanation = self.extract_section(review_result, "IMPROVEMENT EXPLANATION")
            
            # If code fixes were provided, execute the fixed code
            fixed_code_execution_result = ""
            fixed_code_success = False
            if fixed_code and not success:
                logger.info("Executing fixed code")
                fixed_code_success, fixed_code_execution_result = self.execute_python_code(
                    fixed_code, state, scored_text=purpose
                )
            
            # Create the coding review report
            review_report = {
                "status": "completed",
                "original_code": clean_code,
                "review": review,
                "execution_analysis": execution_analysis,
                "fixed_code": fixed_code,
                "improvement_explanation": improvement_explanation,
                "original_execution": {
                    "success": success,
                    "result": execution_result
                },
                "fixed_execution": {
                    "success": fixed_code_success,
                    "result": fixed_code_execution_result
                } if fixed_code else None,
                "timestamp": datetime.now().isoformat()
            }
            
            # Add the report to the state
            state.update_with_agent_output("coding_review", review_report)
            
            logger.info("Coding Review Agent completed successfully")
            return state
            
        except Exception as e:
            logger.error(f"Error in Coding Review Agent: {str(e)}", exc_info=True)
            state.mark_error(f"Coding Review Agent error: {str(e)}")
            return state
    
    def clean_code(self, code: str) -> str:
        """Clean up code by removing markdown formatting and fixing common issues."""
        if not code:
            return ""
            
        # Remove markdown code block markers
        clean_code = code
        if clean_code.startswith("```") and clean_code.endswith("```"):
            clean_code = clean_code[3:-3].strip()
            
        # Remove language identifier if present
        if clean_code.startswith("python"):
            clean_code = clean_code[6:].strip()
            
        # Fix common escaped characters
        clean_code = clean_code.replace("\\n", "\n").replace('\\"', '"').replace("\\t", "\t")
        
        # Use LLM to further clean up the code if available.
        if hasattr(self, 'llm_clean_code'):
            try:
                llm_cleaned_code = self.llm_clean_code(clean_code)
                if llm_cleaned_code:
                    clean_code = llm_cleaned_code
            except Exception as e:
                logger.warning("LLM cleaning failed, using basic cleaned code", exc_info=True)

        return clean_code
    
    def extract_section(self, text: str, section_name: str) -> str:
        """Extract a section from the review result."""
        pattern = rf"{section_name}:(.*?)(?:\n[A-Z ]+:|```|$)"
        match = re.search(pattern, text, re.DOTALL)
        if match:
            return match.group(1).strip()
        return ""
    
    def extract_code(self, text: str) -> str:
        """Extract code from markdown code blocks."""
        code_blocks = re.findall(r'```(?:python)?\s*(.*?)```', text, re.DOTALL)
        if code_blocks:
            return max(code_blocks, key=len).strip()
        return ""
    
    def execute_python_code(self, code: str, state: Optional[WorkflowState] = None,
                            scored_text: Optional[str] = None) -> tuple:
        """Execute Python code and return the result."""
        from app.core.config import settings

        if not getattr(settings, "ENABLE_CODE_EXECUTION", False):
            return False, "Code execution is disabled on this server"
        if not code:
            return False, "No code provided"
        if state is not None:
            import asyncio
            import concurrent.futures

            async def _guarded():
                return await guard_tool(
                    "tool::execute_code",
                    {"code": code},
                    state,
                    principal="coding_review",
                    # What the code is for, checked against the user's intent (checkpoint2-intent SEC-107).
                    scored_text=scored_text,
                )

            try:
                asyncio.get_running_loop()
                with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                    allowed = pool.submit(lambda: asyncio.run(_guarded())).result()
            except RuntimeError:
                allowed = asyncio.run(_guarded())
            if not allowed:
                return False, "Code execution was not allowed by the security guard"

        try:
            # Create a temporary file to write the code
            with tempfile.NamedTemporaryFile(suffix='.py', delete=False, mode='w') as temp_file:
                temp_file_path = temp_file.name
                
                # Create a modified version of the code with common fixes
                fixed_code = code
                fixed_code = fixed_code.replace("\\'", "'")
                fixed_code = fixed_code.replace('\\"', '"')
                
                # Fix common issues with string formatting
                for pattern, replacement in [
                    (r"columns=\['([^']+)', '([^']+)', '([^']+)'\]'", r"columns=['\1', '\2', '\3']"),
                    (r"format='([^']+)'s'", r"format='\1s'"),
                    (r'print\("([^"\n]*)$', r'print("\1")'),
                    (r'print\(\'([^\'\n]*)$', r'print(\'\1\')'),
                ]:
                    fixed_code = re.sub(pattern, replacement, fixed_code)
                
                # Create a more robust execution environment
                exec_code = f"""
# Modified for execution and error handling
import sys
import traceback
import io
from contextlib import redirect_stdout, redirect_stderr

# Capture output
output_buffer = io.StringIO()
error_buffer = io.StringIO()

try:
    # Execute the original code
    with redirect_stdout(output_buffer), redirect_stderr(error_buffer):
{self.indent_code(fixed_code, 8)}
    
    # Print any output
    output = output_buffer.getvalue()
    if output:
        print(output, end='')
    
except Exception as e:
    # Capture full traceback
    print(f"Error: {{type(e).__name__}}: {{str(e)}}", file=sys.stderr)
    print(traceback.format_exc(), file=sys.stderr)
    exit(1)
"""
                # Write the modified code to the temp file
                temp_file.write(exec_code)
            
            # Execute the code in a subprocess with timeout
            try:
                result = run_python_file(temp_file_path, self.timeout_seconds)
                
                # Clean up the temporary file
                try:
                    os.remove(temp_file_path)
                except OSError as e:
                    logger.warning(f"Could not remove temporary file: {e}")
                
                # Check for errors
                if result.returncode != 0:
                    return False, f"Execution failed:\n{result.stderr}"
                
                # Check if any output was produced
                output = result.stdout.strip()
                if not output:
                    return True, "Execution successful (no output)"
                    
                return True, output
                
            except subprocess.TimeoutExpired:
                # Clean up on timeout
                try:
                    os.remove(temp_file_path)
                except OSError as e:
                    logger.warning(f"Could not remove temporary file: {e}")
                return False, f"Execution timed out after {self.timeout_seconds} seconds"
                
        except Exception as e:
            return False, f"Error preparing code for execution: {str(e)}\n{traceback.format_exc()}"
    
    def indent_code(self, code: str, spaces: int) -> str:
        """Indent code by a specified number of spaces."""
        indent = ' ' * spaces
        return indent + code.replace('\n', f'\n{indent}')
    
    async def _generate_review(self, prompt_dict: Dict[str, str]) -> str:
        """Generate code review using LLM."""
        prompt = ChatPromptTemplate.from_template(CODING_REVIEW_PROMPT)
        
        if self.openai_llm:
            # Use OpenAI LLM
            chain = prompt | self.openai_llm | StrOutputParser()
            result = await chain.ainvoke(prompt_dict)
        else:
            # Use fallback LLM
            chain = prompt | self.llm | StrOutputParser()
            result = await chain.ainvoke(prompt_dict)
        
        return result

    def llm_clean_code(self, code: str) -> str:
        """
        Clean up code using OpenAI o3-mini model.
        
        This function sends the code to the OpenAI o3-mini model with instructions
        to format it properly and fix any obvious syntax issues.
        
        Args:
            code: The code to clean up
            
        Returns:
            Cleaned code or original code if cleaning fails
        """
        if not code or not self.code_cleaner_model:
            return code
            
        try:
            # Create a prompt for code cleaning
            prompt = f"""You are a Python code formatter. Your only task is to properly format the following 
Python code while preserving all functionality. Fix any obvious syntax errors, 
adjust indentation, and ensure consistent style. Do not add comments, explanations, 
or change the logic. Return only the cleaned code without any markdown formatting.

CODE TO FORMAT:
```python
{code}
```

CLEANED CODE:"""

            # Use the o3-mini model for efficient code cleaning
            messages = [HumanMessage(content=prompt)]
            response = self.code_cleaner_model.invoke(messages)
            cleaned_code = response.content.strip()
            
            # Remove any markdown code block markers if present
            if cleaned_code.startswith("```python"):
                cleaned_code = cleaned_code[len("```python"):].strip()
            if cleaned_code.startswith("```"):
                cleaned_code = cleaned_code[3:].strip()
            if cleaned_code.endswith("```"):
                cleaned_code = cleaned_code[:-3].strip()
                
            # If the cleaned code is empty or unusually short, return the original
            if not cleaned_code or len(cleaned_code) < len(code) * 0.5:
                logger.warning("LLM code cleaning returned unusually short result, using original code")
                return code
                
            return cleaned_code
            
        except Exception as e:
            logger.warning(f"Error in LLM code cleaning: {str(e)}")
            return code  # Return original code if cleaning fails


def get_coding_review_agent():
    """
    Get an instance of the Coding Review Agent.
    
    Returns:
        A callable function that takes a WorkflowState and calls the agent's run method.
        This makes it compatible with LangGraph which expects nodes to be callable.
    """
    agent = CodingReviewAgent()
    
    # Return a callable function instead of the agent directly
    async def coding_review_function(state: WorkflowState) -> WorkflowState:
        """Callable wrapper for the coding review agent"""
        return await agent.run(state)
    
    return coding_review_function 