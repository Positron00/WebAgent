#!/usr/bin/env python
"""
Coding Review Agent Demo
==========================

This demo demonstrates the capabilities of the Coding Review Agent,
which reviews, executes, debugs, and fixes code generated by the Coding Assistant Agent.

Usage:
    python -m backend.demos.coding_review_demo

Requirements:
    - Configured environment variables (check .env.example)
"""

import os
import sys
import asyncio
import logging
import traceback
from datetime import datetime
import tempfile
import json
from pprint import pprint
import subprocess
import re

# Setup path
current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(os.path.dirname(current_dir))
if parent_dir not in sys.path:
    sys.path.insert(0, parent_dir)

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(name)s - %(levelname)s - %(message)s"
)
logger = logging.getLogger("coding_review_demo")

# Import agents and services
from backend.app.agents.coding_assistant import get_coding_assistant_agent
from backend.app.agents.coding_review import get_coding_review_agent
from backend.app.models.task import WorkflowState
from backend.app.core.config import settings
from backend.app.utils.metrics import timing_decorator
from backend.app.services.llm import confirm_llm_selection
from backend.demos.research_results_display import display_research_results

# Sample code tasks with intentional bugs to test the review agent
CODING_TASKS = [
    {
        "title": "Simple Data Processing with Bug",
        "query": "Write a Python function to parse a CSV file containing user data (name, email, age) and return a list of users who are over 18 years old. The function should handle errors gracefully."
    },
    {
        "title": "Incomplete Exception Handling",
        "query": "Create a function that connects to an API, fetches data, and processes it. Include error handling for API timeouts."
    },
    {
        "title": "Performance Issue",
        "query": "Write a function that finds all prime numbers up to a given limit using the Sieve of Eratosthenes algorithm."
    },
    {
        "title": "Security Vulnerability",
        "query": "Create a function that takes a SQL query parameter from user input and executes it against a database."
    }
]

@timing_decorator
async def run_coding_review_demo():
    """Run the coding review agent demo."""
    logger.info("Starting Coding Review Agent Demo")
    
    # Initialize lists to store results for GUI display
    all_results = []
    
    # Ask user to confirm LLM provider and model selection
    print("\n" + "=" * 80)
    print("CODING REVIEW AGENT DEMO")
    print("=" * 80)
    print("This demo requires LLMs for generating and reviewing code.")
    print("Using OpenAI GPT-4o mini")
    
    # Set model directly without interactive prompt
    provider = "openai" 
    model = "gpt-4o-mini"
    
    # Set environment variables for the selected provider and model
    os.environ["CONFIRM_LLM_SELECTION"] = "true"
    os.environ["CONFIRMED_LLM_PROVIDER"] = provider
    os.environ["CONFIRMED_LLM_MODEL"] = model
    
    # Get agents
    print("\nInitializing Agents...")
    coding_agent = get_coding_assistant_agent()
    review_agent = get_coding_review_agent()
    
    # Run through each coding task
    for idx, task in enumerate(CODING_TASKS):
        logger.info(f"\n\n=== TASK {idx+1}: {task['title']} ===\n")
        
        # Create a workflow state for this task
        state = WorkflowState(
            query=task["query"],
            context={
                "language": "python",
                "code_style": "modern",
                "include_comments": True,
                "include_examples": True
            }
        )
        
        # Run coding assistant agent
        logger.info(f"Generating code for: {task['title']}")
        print(f"\nGenerating code with {provider} ({model}) as the LLM provider...")
        print(f"Task: {task['title']}")
        print(f"Query: {task['query']}")
        
        try:
            start_time = datetime.now()
            coding_result_state = await coding_agent(state)
            coding_duration = (datetime.now() - start_time).total_seconds()
            
            logger.info(f"Code Generation completed in {coding_duration:.2f} seconds")
            
            # Extract code from the reports
            if "coding_assistant" in coding_result_state.reports:
                coding_report = coding_result_state.reports["coding_assistant"]
                if isinstance(coding_report, dict):
                    code = coding_report.get("code", "")
                    explanation = coding_report.get("explanation", "")
                    
                    print("\nGenerated Code:")
                    print("```python")
                    print(code)
                    print("```\n")
                    
                    # Now run the code review agent
                    logger.info("Running Code Review Agent")
                    print("\nReviewing and debugging the generated code...")
                    
                    start_time = datetime.now()
                    review_result_state = await review_agent(coding_result_state)
                    review_duration = (datetime.now() - start_time).total_seconds()
                    
                    logger.info(f"Code Review completed in {review_duration:.2f} seconds")
                    
                    # Extract review results
                    if "coding_review" in review_result_state.reports:
                        review_report = review_result_state.reports["coding_review"]
                        
                        print("\n=== CODE REVIEW RESULTS ===\n")
                        
                        if "review" in review_report:
                            print("REVIEW:")
                            print(review_report["review"])
                            print()
                        
                        if "execution_analysis" in review_report:
                            print("EXECUTION ANALYSIS:")
                            print(review_report["execution_analysis"])
                            print()
                        
                        original_success = review_report.get("original_execution", {}).get("success", False)
                        original_result = review_report.get("original_execution", {}).get("result", "")
                        
                        print(f"ORIGINAL CODE EXECUTION: {'Success' if original_success else 'Failed'}")
                        print(original_result)
                        print()
                        
                        if "fixed_code" in review_report and review_report["fixed_code"]:
                            print("FIXED CODE:")
                            print("```python")
                            print(review_report["fixed_code"])
                            print("```\n")
                            
                            fixed_success = review_report.get("fixed_execution", {}).get("success", False)
                            fixed_result = review_report.get("fixed_execution", {}).get("result", "")
                            
                            print(f"FIXED CODE EXECUTION: {'Success' if fixed_success else 'Failed'}")
                            print(fixed_result)
                            print()
                            
                        if "improvement_explanation" in review_report:
                            print("IMPROVEMENT EXPLANATION:")
                            print(review_report["improvement_explanation"])
                            print()
                        
                        # Store results for display
                        all_results.append({
                            "task": task["title"],
                            "query": task["query"],
                            "original_code": code,
                            "review": review_report.get("review", ""),
                            "execution_analysis": review_report.get("execution_analysis", ""),
                            "fixed_code": review_report.get("fixed_code", ""),
                            "improvement_explanation": review_report.get("improvement_explanation", ""),
                            "original_execution": {
                                "success": original_success,
                                "result": original_result
                            },
                            "fixed_execution": review_report.get("fixed_execution", {})
                        })
                    else:
                        print("No review results found in workflow state")
                else:
                    print("Invalid coding assistant report format")
            else:
                print("No coding assistant results found in workflow state")
            
        except Exception as e:
            logger.error(f"Error running agents: {e}")
            print(f"Error: {str(e)}")
            traceback.print_exc()
    
    # Display results in a structured format
    logger.info("\nDisplaying summary of all results...")
    try:
        display_research_results(
            queries=[task["query"] for task in CODING_TASKS],
            results=all_results,
            errors=[None] * len(CODING_TASKS),
            title="Coding Review Agent Results"
        )
    except Exception as e:
        logger.error(f"Error displaying results: {e}")
    
    logger.info("Coding Review Agent Demo completed.")

if __name__ == "__main__":
    # Run the demo
    asyncio.run(run_coding_review_demo()) 